# --------------------------------------------------------------------------
# Forward operation.
#
# This is the whole of what the rungs above specify.  Equal weights reduce the dot
# product to a count, so the stored value is a threshold and the cell fires when
# the count reaches it.
# --------------------------------------------------------------------------


def threshold_gate(active_counts, thresholds):
    """Fire where the count of active inputs reaches the stored threshold.

    Integer comparison only.  No weights and no multiply, because equal weights
    reduce the dot product to a count; no gradient, because nothing here is
    differentiated.

    This covers the excitatory case and nothing else.  Callers must not route an
    inhibitory or gain edge through it: see `signed_forward`.
    """
    if len(active_counts) != len(thresholds):
        raise ValueError("one threshold per neuron")
    return [c >= t for c, t in zip(active_counts, thresholds)]


def signed_forward(*args, **kwargs):
    """The forward operation this section actually needs, and it is not specified.

    A count of active inputs compared against a threshold has no term for a
    negative contribution.  Four of the internal edges above are inhibitory and
    the biology names them by transmitter — gamma-aminobutyric acid and glycine —
    so this is not an inference about the tissue.  Reciprocal inhibition,
    autogenic inhibition and recurrent inhibition are three of the six reflex
    arcs, and the pain gate is inhibitory at the first synapse of the incoming
    line, so dropping the sign does not approximate the cord: it produces one in
    which antagonists co-contract, motor output has no gain control, and the
    descending analgesic gate excites the pain line.

    The descending gate is a third case and not a sign.  It carries no stimulus
    content, only a multiplier on another edge's transfer, so it is not an input
    to a neuron and has nowhere to go in a sum of inputs.

    Extending the model changes the stored value per neuron and therefore changes
    the parameter-memory derivation for every structure in the map, which puts it
    above this rung.
    """
    raise NotImplementedError(
        "the threshold-gate model has no signed term; four internal edges here are "
        "inhibitory and one incoming edge is a gain. Extending the model changes "
        "the sizing derivation and is not this rung's to choose."
    )



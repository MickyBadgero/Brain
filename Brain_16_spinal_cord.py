"""Brain — spinal cord: grey matter, white matter, and the intrinsic reflex circuitry.

Structures, edges and the threshold-gate forward operation for the segmental
sensorimotor core.  Each neuron is a threshold gate over equal-weight inputs: it
fires when the count of active inputs crosses a stored threshold, so the only value
held per neuron is that threshold, at log2(fan-in) bits.  No weights, no multiply,
no gradient.

Counting basis is uniform here and is not the map's usual one.  The cord is
bilateral-segmental rather than hemispheric, so counts are whole (both sides), with
the per-side value alongside where the biology records one.  That is a fourth basis
after per eye, both eyes combined, and per hemisphere.

Three things separate this module from the visual-pathway one.

First, three edge latencies are real numbers rather than None.  The lamina I
projection to the posterior thalamus carries three labelled lines whose central
conduction times are about 131, 59 and 72 ms — three delays on one anatomical edge,
the slowest 2.2x the fastest.  Everything else reads None, meaning to derive.

Second, the forward operation below cannot express most of what this tissue does.
Inhibition is what the cord computes with: reciprocal inhibition, autogenic
inhibition and recurrent inhibition are three of the six reflex arcs, the pain gate
is inhibitory at the first synapse, and the dorsal-horn interneurons divide by
transmitter into inhibitory and excitatory classes.  A count of active inputs
compared against a threshold has no term for a negative contribution.  Edges carry
their sign here so the gap is visible rather than silently dropped; adding a signed
term to the model is a change to the sizing derivation and is not this rung's.

Third, two of the loops closed inside this tissue run through muscle.  The stretch
reflex's input is muscle length and the gamma loop passes through an intrafusal
spindle fibre, and muscle is outside the scope boundary at every rung.  Those loops
can be declared and cannot be closed.

Four items this module needs are unset at every rung above and each is on the list
that must be surfaced before it is touched: the inter-structure connection topology,
the tile geometry, the sparsity, and the scheduling discipline.  Where each is
needed the module raises rather than choosing.  The learning rule is unset too, and
is the one whose absence still leaves a runnable artifact: thresholds are read-only
construction constants and nothing writes them.
"""

from __future__ import annotations

from dataclasses import dataclass
from math import ceil, log2

# --------------------------------------------------------------------------
# Element classes.
#
# Four kinds appear on or at the boundary of this section and only the first has
# a specified computation.  A pacemaker is here because the presympathetic drive
# onto the intermediolateral cell column is generated by intrinsically pacemaking
# cells rather than relayed: a threshold gate with no active inputs never fires,
# so a cell that fires from nothing is not one under any fan-in.
# --------------------------------------------------------------------------

THRESHOLD_GATE = "threshold_gate"   # spikes; stores a threshold at log2(fan-in) bits
GRADED = "graded"                   # computes without spiking; store not established
PACEMAKER = "pacemaker"             # fires without input; not a threshold gate
NONE_PRESENT = "none"               # fibre columns: no neurons, no synapse, no store

# --------------------------------------------------------------------------
# Edge sign.
#
# The threshold-gate forward operation has no term for a negative contribution.
# The sign is carried anyway, on every edge the biology types, because dropping
# it would produce a cord in which antagonist muscles co-contract, motor output
# has no gain control, and the descending analgesic gate excites the pain line.
#
# GAIN is a third value and not a sign: the descending gate carries no stimulus
# content at all, only a multiplier on another edge's transfer.  It is not an
# input to a neuron and has no place in a sum of active inputs.
# --------------------------------------------------------------------------

EXCITATORY = "+"
INHIBITORY = "-"
GAIN = "gain"                       # modulates another edge; not an input
UNTYPED = None                      # the biology does not type it here

# --------------------------------------------------------------------------
# Structures.
#
# Counts are the architecture's, carried with their basis.  `fan_in` is the
# convergence onto one neuron of this population where the biology fixes it, and
# None where it does not.  Not one fan-in in this section is fixed.
# --------------------------------------------------------------------------


@dataclass(frozen=True)
class Population:
    name: str
    kind: str
    basis: str
    count: int | None            # None where the biology has not fixed it
    fan_in: int | None           # None where the biology has not fixed it
    fan_in_bound: int = 16       # log2 cap: any fan-in under ~65,000 fits 16 bits

    @property
    def threshold_bits(self) -> int | None:
        """Stored bits per neuron under the threshold-gate model."""
        if self.kind == NONE_PRESENT:
            return 0
        if self.kind in (GRADED, PACEMAKER):
            return None          # not zero, and not log2(fan-in): not established
        if self.fan_in is None:
            return self.fan_in_bound
        if self.fan_in <= 1:
            return 0             # nothing to threshold against a single input
        return ceil(log2(self.fan_in))

    @property
    def parameter_bytes(self) -> int | None:
        bits = self.threshold_bits
        if bits is None or self.count is None:
            return None
        return self.count * bits // 8


@dataclass(frozen=True)
class Structure:
    name: str
    populations: tuple[Population, ...]
    subelements: tuple[str, ...] = ()
    adds_tissue: bool = True     # False where the entry is a circuit, not a structure

    @property
    def parameter_bytes(self) -> int | None:
        """None if any population's store is unstated — a partial sum would read as a total."""
        total = 0
        for p in self.populations:
            b = p.parameter_bytes
            if b is None:
                return None
            total += b
        return total



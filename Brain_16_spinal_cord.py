def occupies(subelement: str, segment: str) -> bool:
    """Whether a sub-element exists at a segment.

    Only the three level-restricted cell groups are constrained; the laminae
    themselves run the length of the cord.  The two enlargements are a density
    fact rather than a presence fact and are not represented here, because the
    biology gives no per-segment count to represent them with.
    """
    if subelement not in LEVEL_RESTRICTED:
        return True
    lo, hi = LEVEL_RESTRICTED[subelement]
    i = SEGMENT_ORDER.index(segment)
    return SEGMENT_ORDER.index(lo) <= i <= SEGMENT_ORDER.index(hi)



def sizing_report() -> str:
    lines, total, unstated, excluded = [], 0, [], []
    lines.append(f"{'structure / population':58} {'basis':18} {'neurons':>13} {'bits':>5} {'store':>12}")
    for s in STRUCTURES:
        for p in s.populations:
            bits = p.threshold_bits
            b = p.parameter_bytes
            count = f"{p.count:,}" if p.count is not None else "to derive"
            bs = "-" if bits is None else str(bits)
            if b is None:
                store = "to derive"
                unstated.append(f"{s.name} / {p.name}")
            elif not s.adds_tissue:
                store = "0 (shared)"
                excluded.append(s.name)
            else:
                store = f"{b/1e6:.1f} MB"
                total += b
            lines.append(f"{s.name + ' / ' + p.name:58} {p.basis:18} {count:>13} {bs:>5} {store:>12}")
    lines.append("")
    lines.append(f"stated total: {total/1e6:.1f} MB = {total/1e9:.3f} GB   (whole cord, both sides)")
    lines.append(f"range on the count: {197_000_000*2/1e6:.0f}-{222_000_000*2/1e6:.0f} MB "
                 f"across 197-222M neurons")
    for e in excluded:
        lines.append(f"excluded from the total, adds no tissue: {e}")
    for u in unstated:
        lines.append(f"unstated, so the total is a floor: {u}")
    return "\n".join(lines)


def realisation_gap() -> str:
    """The derived width against the width a machine integer actually takes.

    Every threshold here sits at the 16-bit log2 cap because no fan-in is fixed,
    and 16 bits is a container width, so derived and realised coincide.  The gap
    closes because nothing is derived, not because anything is known, and it
    re-opens the moment one fan-in is measured.
    """
    out = []
    for fan_in in (None, 4, 200, 5_000, 150_000):
        if fan_in is None:
            derived, label = 16, "unfixed (log2 cap)"
        else:
            derived, label = ceil(log2(fan_in)), f"fan-in {fan_in:,}"
        container = 8 if derived <= 8 else (16 if derived <= 16 else 32)
        d = 200_000_000 * derived / 8
        r = 200_000_000 * container / 8
        out.append(
            f"  {label:20} -> {derived:2} bits derived = {d/1e6:6.1f} MB, "
            f"uint{container} realised = {r/1e6:6.1f} MB, gap {100*(r-d)/d:4.1f}%"
        )
    return "\n".join(out)


def ragged_cells() -> str:
    """Which (sub-element, segment) cells the biology says do not exist.

    A dense allocation over all 31 segments asserts tissue at levels the biology
    denies, so the count is reported before any array is shaped.
    """
    out, absent = [], 0
    for sub in LEVEL_RESTRICTED:
        present = [s for s in SEGMENT_ORDER if occupies(sub, s)]
        gone = len(SEGMENT_ORDER) - len(present)
        absent += gone
        out.append(f"  {sub:34} present at {len(present):2}/{len(SEGMENT_ORDER)} segments "
                   f"({present[0]}-{present[-1]}), absent at {gone}")
    dense = LAMINAE * SIDES * len(SEGMENT_ORDER)
    out.append(f"  dense (lamina, side, segment) cells: {dense}")
    out.append(f"  cells a dense allocation would assert wrongly, per side: {absent}")
    out.append(f"  even division of 200M over {dense} cells would be "
               f"{200_000_000 // dense:,} each — an invention, not a partition")
    return "\n".join(out)


def edge_storage(update_interval_s: float, line_count: int, bits_per_value: int = 1) -> str:
    """Values in flight on the measured edges, given an update interval.

    edge_storage = line_count * ceil(latency / update_interval) * bits_per_value

    This section is the first with real latencies to put in that formula, and it is
    still not sizable, because the update interval is the scheduling discipline and
    that is unset and Micky's.  Both terms are therefore arguments with no default:
    supplying one would be choosing the discipline inside a helper.

    Storage scales with the reciprocal of the interval, so halving the interval
    doubles the memory held on every edge — which is what ties the timing decision
    to a resource rather than only to correctness.
    """
    if update_interval_s <= 0:
        raise ValueError("an update interval of zero asserts an infinite rate")
    out = []
    total = 0
    for e in EDGES:
        if e.latency_s is None:
            continue
        slots = ceil(e.latency_s / update_interval_s)
        bits = line_count * slots * bits_per_value
        total += bits
        out.append(f"  {e.carries[:34]:36} {e.latency_s*1000:5.0f} ms -> "
                   f"{slots:6,} slots, {bits/8/1e6:8.2f} MB")
    out.append(f"  total on the measured edges: {total/8/1e6:.2f} MB "
               f"at {update_interval_s*1000:g} ms and {line_count:,} lines per line class")
    return "\n".join(out)


def latency_report() -> str:
    stated = [e for e in EDGES if e.latency_s is not None]
    lines = [f"edges: {len(EDGES)}    with a stated latency: {len(stated)}    "
             f"to derive: {len(EDGES) - len(stated)}"]
    for e in stated:
        lines.append(f"  {e.source_sub or e.source} -> {e.target}: "
                     f"{e.latency_s*1000:.0f} ms  ({e.carries})")
    if stated:
        lo = min(e.latency_s for e in stated)
        hi = max(e.latency_s for e in stated)
        lines.append(f"  spread on one anatomical edge: {hi/lo:.1f}x")
    lines.append(f"internal edges: {len(INTERNAL_EDGES)}    with a stated latency: 0")
    return "\n".join(lines)


def sign_report() -> str:
    """How much of this section the unsigned forward operation can express."""
    counts: dict[str, int] = {}
    for e in INTERNAL_EDGES:
        counts[str(e.sign)] = counts.get(str(e.sign), 0) + 1
    for e in EDGES:
        if e.sign is not None and not e.routing_only:
            counts[str(e.sign)] = counts.get(str(e.sign), 0) + 1
    out = [f"  {k:6} {v}" for k, v in sorted(counts.items())]
    blocked = counts.get(INHIBITORY, 0) + counts.get(GAIN, 0)
    out.append(f"  edges the unsigned forward operation cannot express: {blocked}")
    out.append(f"  loops that leave the scope boundary: "
               f"{sum(1 for e in INTERNAL_EDGES if e.leaves_scope)}")
    return "\n".join(out)


def far_end_report() -> str:
    """Endpoints whose entry lives in another source file, and the two with none."""
    seen: dict[str, str] = {}
    for e in EDGES:
        if e.off_file:
            key = e.target if e.source.startswith("spinal") else e.source
            seen.setdefault(key, e.off_file)
    out = [f"  {k:44} {v}" for k, v in sorted(seen.items())]
    return "\n".join(out)


